class FamilyLinkSerializer(serializers.ModelSerializer):
    family_user_id = serializers.IntegerField(read_only=True)
    family_email = serializers.EmailField(source="family_user.email", read_only=True)
    family_display_name = serializers.CharField(source="family_user.display_name", read_only=True)
    consent_id = serializers.IntegerField(read_only=True)
    access_active = serializers.SerializerMethodField()

    class Meta:
        model = FamilyLink
        fields = [
            "id", "family_user_id", "family_email", "family_display_name", "relationship",
            "consent_id", "is_active", "access_active",
        ]
        read_only_fields = fields

    def get_access_active(self, obj) -> bool:
        """True only while the link is on AND the family_view consent it rests on is still active."""
        consent = obj.consent
        return bool(obj.is_active and consent.revoked_at is None and consent.scope == services.FAMILY_SCOPE)


