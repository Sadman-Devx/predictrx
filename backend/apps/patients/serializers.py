SEX_CHOICES = ("male", "female", "other")
MIN_BIRTH_YEAR = 1900
MAX_WEIGHT_KG = 500
CONSENT_SCOPES = [value for value, _label in Consent.SCOPES]
SEVERITY_LEVELS = ["major", "moderate", "minor", "unknown"]


# ------------------------------------------------------------------------------------------------ patients
class PatientSerializer(serializers.ModelSerializer):
    sex = serializers.ChoiceField(choices=SEX_CHOICES, required=False, allow_blank=True)
    # Read-only, computed by the server. Nothing here is guessed by the UI (design.md §1.2 / ConsentBanner).
    consent_active = serializers.SerializerMethodField()
    active_consent_scopes = serializers.SerializerMethodField()
    medication_count = serializers.SerializerMethodField()

    class Meta:
        model = Patient
        fields = [
            "id", "patient_code", "birth_year", "sex", "weight_kg", "created_at",
            "consent_active", "active_consent_scopes", "medication_count",
        ]
        # `owner` is not exposed at all; `patient_code` is generated by the server.
        read_only_fields = ["id", "patient_code", "created_at"]

    def validate_birth_year(self, value):
        if value is None:
            return value
        if not MIN_BIRTH_YEAR <= value <= date.today().year:
            raise serializers.ValidationError(f"Birth year must be between {MIN_BIRTH_YEAR} and {date.today().year}.")
        return value

    def validate_weight_kg(self, value):
        if value is None:
            return value
        if not 0 < value <= MAX_WEIGHT_KG:
            raise serializers.ValidationError(f"Weight must be greater than 0 and at most {MAX_WEIGHT_KG} kg.")
        return value

    def get_consent_active(self, obj) -> bool:
        """True while the patient's `analysis` consent is active (scans and analysis depend on it)."""
        return services.ANALYSIS_SCOPE in services.active_consent_scopes(obj)

    def get_active_consent_scopes(self, obj) -> list[str]:
        return services.active_consent_scopes(obj)

    def get_medication_count(self, obj) -> int:
        return services.medication_count(obj)


